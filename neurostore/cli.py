"""Command line interface: ``neurostore {scaffold,run,report,list}``.

This replaces the original ``neurostore_cli.py``, whose ``main()`` did not parse
(``run_parser subparsers.add_parser(...)`` lacks the ``=``) and whose ``run`` command covered
only part of three workloads.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Sequence

from . import __version__
from .baselines import availability
from .profiles import PROFILES, get_profile
from .report import RENDERERS, render_report, scorecard
from .results import SuiteResult, WorkloadResult
from .runner import ORDER, parse_workloads, run_suite, selfcheck_failures

SCAFFOLD_README = """# NeuroStore benchmark workspace

Generated by `neurostore scaffold`.

    config.json   the full {profile!r} profile; edit any value and run with --config
    results/      default output directory

Run the suite:

    neurostore run --config config.json --out results/my-run

Re-render a report from stored results:

    neurostore report results/my-run/results.json
"""


def _log(msg: str) -> None:
    print(msg, file=sys.stderr, flush=True)


def cmd_scaffold(args: argparse.Namespace) -> int:
    root = Path(args.dir)
    root.mkdir(parents=True, exist_ok=True)
    (root / "results").mkdir(exist_ok=True)
    files = {
        root / "README.md": SCAFFOLD_README.format(profile=args.profile),
        root / "config.json": json.dumps(get_profile(args.profile), indent=2) + "\n",
    }
    for path, content in files.items():
        if path.exists() and not args.force:
            print(f"keep   {path} (exists; use --force to overwrite)")
        else:
            path.write_text(content)
            print(f"wrote  {path}")
    print(f"Benchmark workspace ready in {root}/")
    return 0


def cmd_list(_args: argparse.Namespace) -> int:
    print("Workloads:")
    from .workloads import WORKLOADS

    for k in ORDER:
        print(f"  {k:<9} {WORKLOADS[k].TITLE}")
    print("\nProfiles: " + ", ".join(PROFILES))
    print("\nBaselines:")
    for name, info in availability().items():
        status = "available" if info["available"] else f"MISSING ({info['reason']})"
        print(f"  {name:<24} [{info['family']:<4}] {info['description']} -- {status}")
    return 0


def cmd_run(args: argparse.Namespace) -> int:
    overrides = json.loads(Path(args.config).read_text()) if args.config else None
    # a --config file may be a whole profile dump (scaffold) or a sparse override; both are per-workload dicts
    try:
        keys = parse_workloads(args.workload)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    verbose = not args.quiet

    def show(res: WorkloadResult) -> None:
        if args.format == "markdown":
            print(f"\n## {res.title}\n")
            if res.workload in RENDERERS and res.tables:
                print(RENDERERS[res.workload](res))
            for c in res.checks:
                mark = {True: "PASS", False: "FAIL", None: "info"}[c["passed"]]
                print(f"  [{mark}] {c['name']}: {c['measured']}")
            print(f"  ({res.elapsed_s:.0f} s)", flush=True)

    suite = run_suite(keys, profile=args.profile, seed=args.seed, overrides=overrides, include_external=not args.no_external,
                      threads=args.threads, log=_log if verbose else None, on_result=show if verbose else None, fail_fast=args.fail_fast)
    if args.out:
        out = Path(args.out)
        suite.save(out / "results.json")
        (out / "REPORT.md").write_text(render_report(suite))
        print(f"\nwrote {out / 'results.json'} and {out / 'REPORT.md'}")
    rows, tally = scorecard(suite)
    if rows:
        print(f"\nScorecard tally over {sum(tally.values())} comparisons: {tally['WIN']} win / {tally['TIE']} tie / {tally['LOSS']} loss")
    bad = selfcheck_failures(suite)
    for w, c in bad:
        print(f"SELF-CHECK FAILED [{w}] {c['name']}: {c['measured']}", file=sys.stderr)
    return 2 if (bad and args.strict) else 0


def cmd_report(args: argparse.Namespace) -> int:
    suite = SuiteResult.load(args.results)
    text = render_report(suite)
    if args.output:
        Path(args.output).write_text(text)
        print(f"wrote {args.output}")
    else:
        print(text)
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="neurostore", description="NeuroStore neural-coding benchmark and evaluation framework")
    parser.add_argument("--version", action="version", version=f"neurostore {__version__}")
    sub = parser.add_subparsers(dest="command", help="sub-command to run")

    sp = sub.add_parser("scaffold", help="initialise a benchmark workspace (config + results directory)")
    sp.add_argument("--dir", default="benchmark_workspace", help="workspace directory (default: ./benchmark_workspace)")
    sp.add_argument("--profile", choices=sorted(PROFILES), default="standard")
    sp.add_argument("--force", action="store_true", help="overwrite existing files")
    sp.set_defaults(func=cmd_scaffold)

    rp = sub.add_parser("run", help="run benchmark workloads")
    rp.add_argument("-w", "--workload", default="all", help=f"comma-separated subset of {ORDER} or 'all' (default: all)")
    rp.add_argument("--profile", choices=sorted(PROFILES), default="standard", help="quick: seconds, standard: minutes, full: tens of minutes")
    rp.add_argument("--seed", type=int, default=0)
    rp.add_argument("--config", help="JSON file of per-workload overrides, e.g. {\"a\": {\"trials\": 500}}")
    rp.add_argument("--out", help="directory for results.json and REPORT.md")
    rp.add_argument("--threads", type=int, default=None, help="BLAS/OpenMP/FAISS threads (profile default: 1; 0 = library default)")
    rp.add_argument("--no-external", action="store_true", help="skip FAISS/Qdrant/RocksDB/Redis/datasketch baselines")
    rp.add_argument("--quiet", action="store_true", help="no progress or per-workload output")
    rp.add_argument("--format", choices=("markdown", "none"), default="markdown")
    rp.add_argument("--strict", action="store_true", help="exit with status 2 if any benchmark self-check fails")
    rp.add_argument("--fail-fast", action="store_true", help="re-raise the first workload exception")
    rp.set_defaults(func=cmd_run)

    rr = sub.add_parser("report", help="render a Markdown report from a results.json")
    rr.add_argument("results")
    rr.add_argument("-o", "--output")
    rr.set_defaults(func=cmd_report)

    ls = sub.add_parser("list", help="list workloads, profiles and baseline availability")
    ls.set_defaults(func=cmd_list)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    if not getattr(args, "func", None):
        parser.print_help()
        return 0
    return int(args.func(args) or 0)


if __name__ == "__main__":
    raise SystemExit(main())
