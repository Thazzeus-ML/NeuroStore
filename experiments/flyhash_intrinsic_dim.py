"""EXPLORATORY (not part of the reference benchmark run): does FlyHash-vs-SimHash depend on the data's intrinsic dimension?

Workload C's synthetic embeddings are isotropic Gaussian mixtures, i.e. they have the *highest* possible intrinsic
dimension. FlyHash's published advantages are on structured, low-intrinsic-dimension data, so the obvious objection to
"SimHash beats FlyHash at equal bits" is that the data is unkind to FlyHash. This script tests it.

Embeddings live on a ``latent``-dimensional linear manifold inside R^d (random orthonormal embedding of a topic-mixture),
and paraphrases perturb the *latent* code so they stay on the manifold. Low-dimensional spaces are crowded with
near-duplicates, so paraphrase strength is chosen per latent dimension to keep the task solvable (the exact-cosine scan
column shows that it is); codes are then compared at equal difficulty.

    python experiments/flyhash_intrinsic_dim.py [--n-cache 10000] [--seed 3] [--out results/exploratory/flyhash_intrinsic_dim.md]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from neurostore.baselines.cache import BruteForceCosineCache, FlyHashInvertedCache, SimHashCache  # noqa: E402
from neurostore.common import limit_threads, make_rng  # noqa: E402
from neurostore.report import md_table  # noqa: E402
from neurostore.workloads.c_prompt_cache import _calibrated_metrics, _unit  # noqa: E402

GRID = {8: (0.995, 0.99, 0.98), 16: (0.98, 0.97, 0.95), 32: (0.95, 0.92, 0.90), 128: (0.80, 0.70, 0.60)}
SYSTEMS = [
    ("exact cosine", lambda: BruteForceCosineCache()),
    ("SimHash 2048 bits", lambda: SimHashCache(2048)),
    ("SimHash 512 bits", lambda: SimHashCache(512)),
    ("FlyHash m=2048 k=64", lambda: FlyHashInvertedCache(2048, 64)),
    ("FlyHash m=4096 k=205", lambda: FlyHashInvertedCache(4096, 205)),
    ("FlyHash m=8192 k=410", lambda: FlyHashInvertedCache(8192, 410)),
]


def manifold_dataset(seed: int, n_cache: int, d: int, latent: int, para: float, topics: int = 20, rho: float = 0.5, n_pos: int = 1000, n_neg: int = 1000) -> dict:
    rng = make_rng(seed)
    basis, _ = np.linalg.qr(rng.standard_normal((d, latent)))
    centers = _unit(rng.standard_normal((topics, latent)))

    def prompts(n: int) -> np.ndarray:
        t = rng.integers(0, topics, n)
        g = _unit(rng.standard_normal((n, latent)))
        return _unit(np.sqrt(rho) * centers[t] + np.sqrt(1 - rho) * g)

    def embed(z: np.ndarray) -> np.ndarray:
        return _unit(z @ basis.T)

    zc = prompts(n_cache)
    src = rng.integers(0, n_cache, n_pos)
    u = rng.standard_normal((n_pos, latent))
    u -= (u * zc[src]).sum(axis=1, keepdims=True) * zc[src]
    return {"cache": embed(zc), "pos_q": embed(para * zc[src] + np.sqrt(1 - para**2) * _unit(u)), "pos_src": src, "neg_q": embed(prompts(n_neg)), "calib_q": embed(prompts(n_neg))}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--n-cache", type=int, default=10_000)
    ap.add_argument("--seed", type=int, default=3)
    ap.add_argument("--d", type=int, default=128)
    ap.add_argument("--out", default="results/exploratory/flyhash_intrinsic_dim.md")
    args = ap.parse_args()

    rows = []
    with limit_threads(1):
        for latent, paras in GRID.items():
            for para in paras:
                data = manifold_dataset(args.seed, args.n_cache, args.d, latent, para)
                cells = []
                for _, make in SYSTEMS:
                    system = make()
                    system.build(data["cache"])
                    cells.append(f"{_calibrated_metrics(system, data, 0.01, None)['recall_at_1'] * 100:.1f}")
                rows.append([latent, f"{para:g}", *cells])
                print(rows[-1], flush=True)

    text = (
        "# FlyHash vs SimHash across intrinsic dimension (exploratory)\n\n"
        f"Recall@1 (%) on {args.n_cache:,} cached prompts, ambient d={args.d}, seed {args.seed}. Embeddings lie on a `latent`-dimensional linear manifold; paraphrase strength is\n"
        "chosen per latent dimension so the task is solvable (see the exact-cosine column). Generated by `experiments/flyhash_intrinsic_dim.py`; **not** part of the reference run.\n\n"
        + md_table(["latent dim", "paraphrase cosine", *[name for name, _ in SYSTEMS]], rows)
        + "\nMemory per prompt (inverted index / packed code): SimHash-2048 256 B, SimHash-512 64 B, FlyHash 2048/64 ~258 B, 4096/205 ~823 B, 8192/410 ~1647 B.\n"
    )
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
